//go:build nativemetadatalockorder

package tsdb

import (
	"bytes"
	"fmt"
	"runtime"
	"strconv"
	"strings"
	"sync"
)

// A test build with the nativemetadatalockorder tag records, per goroutine,
// the series, stripe and repair locks it holds, and records a violation of
// the native metadata repairs' lock order before the lock that would violate
// it is taken:
//   - nothing is locked while the repair mutex is held;
//   - the repair mutex isn't taken while a stripe lock is held;
//   - repair code locks no series while it holds a stripe lock or another
//     series' lock.
//
// Tests also check that no such lock is held across a WAL write.

type lockClass int

const (
	lockSeries lockClass = iota
	lockStripe
	lockRepair
	lockClasses
)

var lockClassNames = [lockClasses]string{"series", "stripe", "repair"}

var lockOrder struct {
	mtx sync.Mutex
	// held counts each goroutine's locks by class.
	held       map[uint64]*[lockClasses]int
	violations []string
	// taken counts locks taken by class, and checks the no-lock checks.
	taken  [lockClasses]int64
	checks int64
}

func goroutineID() uint64 {
	var buf [64]byte
	n := runtime.Stack(buf[:], false)
	// The trace starts "goroutine <id> [".
	fields := bytes.Fields(buf[:n])
	id, err := strconv.ParseUint(string(fields[1]), 10, 64)
	if err != nil {
		panic(fmt.Sprintf("parsing goroutine ID from %q: %v", buf[:n], err))
	}
	return id
}

// fromRepairCode reports whether the lock is being taken by native metadata
// repair code.
func fromRepairCode() bool {
	pcs := make([]uintptr, 16)
	frames := runtime.CallersFrames(pcs[:runtime.Callers(3, pcs)])
	for {
		frame, more := frames.Next()
		name := frame.Function
		wrapper := frame.File == "<autogenerated>" || strings.HasSuffix(name, ".(*memSeries).Lock")
		if !wrapper && !strings.Contains(name, "seriesMutex") && !strings.Contains(name, "sync.") {
			return strings.Contains(name, "NativeMetadataRepair") ||
				strings.Contains(name, "PendingNativeMetadataSeries") ||
				strings.Contains(name, "writeNativeMetadataOverrides")
		}
		if !more {
			return false
		}
	}
}

func lockOrderViolation(format string, args ...any) {
	v := fmt.Sprintf(format, args...)
	// A violation can be followed by a deadlock, so it is reported at once too.
	println("native metadata lock order violated:", v)
	lockOrder.violations = append(lockOrder.violations, v)
}

// acquiring checks the lock order before goroutine takes a lock of class c.
func acquiring(c lockClass) {
	id := goroutineID()
	lockOrder.mtx.Lock()
	defer lockOrder.mtx.Unlock()
	lockOrder.taken[c]++
	held := lockOrder.held[id]
	if held == nil {
		return
	}
	switch {
	case held[lockRepair] > 0:
		lockOrderViolation("a %s lock taken while the repair mutex is held", lockClassNames[c])
	case c == lockRepair && held[lockStripe] > 0:
		lockOrderViolation("the repair mutex taken while a stripe lock is held")
	case c == lockSeries && (held[lockStripe] > 0 || held[lockSeries] > 0) && fromRepairCode():
		lockOrderViolation("repair code locked a series while holding %d stripe and %d series locks", held[lockStripe], held[lockSeries])
	}
}

// holding records that the goroutine took (delta 1) or released (delta -1) a
// lock of class c.
func holding(c lockClass, delta int) {
	id := goroutineID()
	lockOrder.mtx.Lock()
	defer lockOrder.mtx.Unlock()
	if lockOrder.held == nil {
		lockOrder.held = map[uint64]*[lockClasses]int{}
	}
	held := lockOrder.held[id]
	if held == nil {
		held = &[lockClasses]int{}
		lockOrder.held[id] = held
	}
	held[c] += delta
	if held[c] < 0 {
		lockOrderViolation("a %s lock released by a goroutine that doesn't hold it", lockClassNames[c])
	}
	if *held == [lockClasses]int{} {
		delete(lockOrder.held, id)
	}
}

// checkNoLockHeld records a violation if the goroutine holds any series,
// stripe or repair lock while it does what.
func checkNoLockHeld(what string) {
	id := goroutineID()
	lockOrder.mtx.Lock()
	defer lockOrder.mtx.Unlock()
	lockOrder.checks++
	if held := lockOrder.held[id]; held != nil {
		lockOrderViolation("%s while holding %d series, %d stripe and %d repair locks", what, held[lockSeries], held[lockStripe], held[lockRepair])
	}
}

// lockOrderCounts returns the locks taken by class, and the no-lock checks.
func lockOrderCounts() (taken [lockClasses]int64, checks int64) {
	lockOrder.mtx.Lock()
	defer lockOrder.mtx.Unlock()
	return lockOrder.taken, lockOrder.checks
}

// resetLockOrder forgets the violations and counts recorded so far.
func resetLockOrder() {
	lockOrder.mtx.Lock()
	defer lockOrder.mtx.Unlock()
	lockOrder.violations, lockOrder.taken, lockOrder.checks = nil, [lockClasses]int64{}, 0
}

// takeLockOrderViolations returns the violations recorded since the last call.
func takeLockOrderViolations() []string {
	lockOrder.mtx.Lock()
	defer lockOrder.mtx.Unlock()
	v := lockOrder.violations
	lockOrder.violations = nil
	return v
}

type seriesMutex struct{ mu sync.Mutex }

func (m *seriesMutex) Lock() {
	acquiring(lockSeries)
	m.mu.Lock()
	holding(lockSeries, 1)
}

func (m *seriesMutex) TryLock() bool {
	acquiring(lockSeries)
	if !m.mu.TryLock() {
		return false
	}
	holding(lockSeries, 1)
	return true
}

func (m *seriesMutex) Unlock() {
	holding(lockSeries, -1)
	m.mu.Unlock()
}

type stripeMutex struct{ mu sync.RWMutex }

func (m *stripeMutex) Lock() {
	acquiring(lockStripe)
	m.mu.Lock()
	holding(lockStripe, 1)
}

func (m *stripeMutex) TryLock() bool {
	acquiring(lockStripe)
	if !m.mu.TryLock() {
		return false
	}
	holding(lockStripe, 1)
	return true
}

func (m *stripeMutex) Unlock() {
	holding(lockStripe, -1)
	m.mu.Unlock()
}

func (m *stripeMutex) RLock() {
	acquiring(lockStripe)
	m.mu.RLock()
	holding(lockStripe, 1)
}

func (m *stripeMutex) TryRLock() bool {
	acquiring(lockStripe)
	if !m.mu.TryRLock() {
		return false
	}
	holding(lockStripe, 1)
	return true
}

func (m *stripeMutex) RUnlock() {
	holding(lockStripe, -1)
	m.mu.RUnlock()
}

type repairMutex struct{ mu sync.Mutex }

func (m *repairMutex) Lock() {
	acquiring(lockRepair)
	m.mu.Lock()
	holding(lockRepair, 1)
}

func (m *repairMutex) Unlock() {
	holding(lockRepair, -1)
	m.mu.Unlock()
}
